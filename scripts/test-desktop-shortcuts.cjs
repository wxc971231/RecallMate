// Native Electron input regression: shortcuts must coexist with typing, IME and modal controls.
module.exports = async ({ evaluate, click, clickAria, fill, until, delay, screenshot, check, target }) => {
  const key = async (keyCode, modifiers = [], type = 'keyDown') => {
    target.webContents.sendInputEvent({ type, keyCode, modifiers }); await delay(100);
  };
  const tap = async (code, mods = []) => { await key(code, mods); await key(code, mods, 'keyUp'); };
  const record = async (action, code, mods = []) => {
    await evaluate(`document.querySelector('#shortcut-${action}').focus()`); await tap(code, mods);
  };
  const index = () => evaluate('document.querySelector(".question-meta").textContent');
  const value = () => evaluate('document.querySelector(".blank-wrap input").value');
  await click('返回题库'); await click('题库'); await click('导入题库');
  await evaluate('document.querySelector("#import-text").focus()');
  await target.webContents.insertText('# 快捷键回归\n{{甲乙}}。\n---\n{{丙丁}}。\n---\n{{戊己}}。');
  await click('导入 3 道题目'); await click('开始练习');
  check(await evaluate('document.querySelector(".hint-button").dataset.shortcut === "F2"'), 'Default shortcut hints appear on practice buttons');
  await fill('第 1 个填空', '甲');
  await key('F1');
  check(await evaluate('!!document.querySelector(".blank-wrap.peeking")') && await value() === '甲', 'Holding F1 reveals answer without replacing draft');
  await key('F1', [], 'keyUp');
  check(await evaluate('!document.querySelector(".peeking") && document.activeElement.matches(".blank-wrap input")'), 'Releasing F1 restores draft and input focus');
  await tap('F2'); check(await value() === '甲乙', 'F2 supplies a hint');
  await tap('F3'); check(await evaluate('!document.querySelector(".given-up")'), 'Unmodified F3 does not give up');
  await tap('F3', ['shift']); check(await evaluate('!!document.querySelector(".given-up")'), 'Shift+F3 gives up');
  await tap('Return'); check((await index()).includes('第 2 题'), 'Enter advances after giving up');
  await key('F4'); check((await index()).includes('第 3 题'), 'F4 skips one question');
  await delay(300); await key('F4', ['isAutoRepeat']);
  check((await index()).includes('第 3 题'), 'Holding skip does not skip several questions');
  await key('F4', [], 'keyUp');
  await click('设置');
  await record('hint', 'F6'); await record('giveUp', 'F6');
  check(await evaluate('[...document.querySelectorAll("button")].find(b=>b.textContent === "保存快捷键").disabled && !!document.querySelector(".shortcut-settings [role=alert]")'), 'Conflicting shortcuts show an error and cannot be saved');
  await record('giveUp', 'F3', ['shift']); await record('answer', 'F1', ['control', 'shift']);
  await record('submit', 'F7'); await clickAria('停用跳过快捷键');
  await evaluate('document.querySelector("button[aria-label=关闭弹窗]").focus()');
  await tap('F2'); check(await value() === '', 'Settings modal blocks practice shortcuts');
  await click('保存快捷键');
  await until('document.querySelector(".shortcut-save-status")?.textContent === "快捷键已保存"', 'custom shortcut save');
  await screenshot('desktop-shortcuts.png');
  await clickAria('关闭弹窗');
  await until('document.querySelector(".save-indicator").textContent.includes("已保存")', 'shortcut session saved');
  await evaluate('location.reload()'); await until('document.querySelector(".bank-row") !== null', 'shortcut reload');
  const settings = await evaluate('window.recallmate.loadSettings()');
  check(settings.settings.shortcuts.hint === 'F6' && settings.settings.shortcuts.answer === 'Ctrl+Shift+F1' && settings.settings.shortcuts.skip === null && settings.settings.shortcuts.submit === 'F7', 'Custom and disabled shortcuts persist through real settings IPC and reload');
  await click('快捷键回归'); await click('继续练习');
  await tap('F1'); await tap('F2'); await tap('F4');
  check(await value() === '' && (await index()).includes('第 3 题') && await evaluate('!document.querySelector(".peeking")'), 'Old bindings and disabled skip no longer trigger');
  await key('F1', ['control', 'shift']);
  check(await evaluate('!!document.querySelector(".peeking")'), 'Custom modifier combination reveals the answer');
  await key('Shift', ['control'], 'keyUp');
  check(await evaluate('!document.querySelector(".peeking")'), 'Releasing a modifier hides the answer');
  await key('F1', [], 'keyUp'); await tap('F6');
  check(await value() === '戊', 'New hint binding supplies one character');
  await key('F6', ['isAutoRepeat']);
  check(await value() === '戊', 'Auto-repeat never supplies another hint');
  await key('F6', [], 'keyUp');
  await evaluate('document.querySelector(".blank-wrap input").dispatchEvent(new CompositionEvent("compositionstart", {bubbles:true}))');
  await tap('F6'); check(await value() === '戊', 'Practice shortcuts pause while IME is composing');
  await evaluate('document.querySelector(".blank-wrap input").dispatchEvent(new CompositionEvent("compositionend", {bubbles:true}))');
  await delay(100); await click('字号'); await tap('F6');
  check(await value() === '戊', 'Font popover pauses practice shortcuts');
  await click('恢复默认字号'); await click('字号');
  check((await evaluate('window.recallmate.loadSettings()')).settings.shortcuts.hint === 'F6', 'Resetting fonts preserves custom shortcuts');
  await fill('第 1 个填空', '戊己'); await tap('Return');
  check(await evaluate('!document.querySelector(".blank-wrap.correct")'), 'Enter no longer submits when rebound');
  await key('F7'); check(await evaluate('!!document.querySelector(".blank-wrap.correct")'), 'Custom submit binding judges the answer');
  await key('F7', ['isAutoRepeat']);
  check(await evaluate('!document.querySelector(".summary-card")'), 'Holding submit does not advance immediately');
  await key('F7', [], 'keyUp'); await tap('F7');
  await until('document.querySelector(".summary-card") !== null', 'custom next shortcut');
  check(true, 'Custom submit binding also advances to the next question');
  await click('设置'); await click('恢复默认快捷键'); await click('保存快捷键');
  await until('document.querySelector(".shortcut-save-status")?.textContent === "快捷键已保存"', 'default shortcut save');
  check((await evaluate('window.recallmate.loadSettings()')).settings.shortcuts.submit === 'Enter', 'Default shortcuts can be restored and persisted');
  await clickAria('关闭弹窗');
};
